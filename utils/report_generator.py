"""
Report Generation Engine for Exporting Analysis Results.
Supports downloadable PDF, DOCX, CSV, and JSON reports.
"""

import io
import json
from typing import Dict, Any, List
import pandas as pd

# Safe ReportLab PDF import
try:
    from reportlab.lib.pagesizes import letter
    from reportlab.lib import colors
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    REPORTLAB_AVAILABLE = True
except ImportError:
    REPORTLAB_AVAILABLE = False

# Safe python-docx import
try:
    import docx
    from docx.shared import Inches, Pt, RGBColor
    DOCX_AVAILABLE = True
except ImportError:
    DOCX_AVAILABLE = False


def generate_json_report(analysis: Dict[str, Any]) -> str:
    """Generate structured JSON report string."""
    return json.dumps(analysis, indent=2)


def generate_csv_report(analysis: Dict[str, Any]) -> str:
    """Generate CSV string of detected accessibility issues."""
    issues = analysis.get("issues", [])
    if not issues:
        df = pd.DataFrame([{
            "Category": "None",
            "Severity": "Info",
            "Title": "No accessibility violations detected",
            "Explanation": "The text passed all cognitive inclusion rule checks.",
            "Suggestion": "None",
            "Confidence": 1.0
        }])
    else:
        df = pd.DataFrame(issues)
        
    return df.to_csv(index=False)


def generate_docx_report(analysis: Dict[str, Any], doc_title: str = "Accessibility Audit Report") -> bytes:
    """Generate DOCX document report bytes."""
    if not DOCX_AVAILABLE:
        doc = docx.Document() if docx else None
        return b"DOCX library (python-docx) is missing."
        
    doc = docx.Document()
    
    # Document Title
    heading = doc.add_heading(doc_title, level=0)
    heading.runs[0].font.color.rgb = RGBColor(99, 102, 241)
    
    doc.add_paragraph(f"Generated by AI-Powered Accessibility Intelligence Dashboard")
    doc.add_paragraph(f"Overall Accessibility Score: {analysis.get('accessibility_score', 0)} / 100")
    
    # Executive Summary Table
    doc.add_heading("Executive Summary KPIs", level=1)
    table = doc.add_table(rows=5, cols=2)
    table.style = 'Table Grid'
    
    kpis = [
        ("Accessibility Score", f"{analysis.get('accessibility_score', 0)} / 100"),
        ("Flesch Reading Ease", f"{analysis.get('readability_score', 0)}"),
        ("Reading Grade Level", f"Grade {analysis.get('grade_level', 0)}"),
        ("Reading Time", f"{analysis.get('reading_time_seconds', 0)} seconds"),
        ("Total Violations Count", f"{analysis.get('violations_count', 0)} issues")
    ]
    
    for i, (key, val) in enumerate(kpis):
        table.cell(i, 0).text = key
        table.cell(i, 1).text = val
        
    doc.add_paragraph()
    
    # Issues Section
    doc.add_heading("Detected Accessibility Violations", level=1)
    issues = analysis.get("issues", [])
    if not issues:
        doc.add_paragraph("No accessibility violations detected. Great job!")
    else:
        for idx, iss in enumerate(issues, 1):
            p = doc.add_paragraph()
            p.add_run(f"#{idx}. {iss.get('title')} [{iss.get('severity')}]").bold = True
            p.add_run(f"\nCategory: {iss.get('category')}")
            p.add_run(f"\nExplanation: {iss.get('explanation')}")
            if iss.get("snippet"):
                p.add_run(f"\nSnippet: \"{iss.get('snippet')}\"")
            if iss.get("suggestion"):
                p.add_run(f"\nSuggestion: {iss.get('suggestion')}")
            doc.add_paragraph()
            
    # Simplified Text Section
    if analysis.get("simplified_text"):
        doc.add_heading("AI Simplified Revision", level=1)
        doc.add_paragraph(analysis["simplified_text"])
        
    buffer = io.BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer.getvalue()


def generate_pdf_report(analysis: Dict[str, Any], doc_title: str = "Accessibility Audit Report") -> bytes:
    """Generate PDF document report bytes using ReportLab."""
    if not REPORTLAB_AVAILABLE:
        return b"PDF library (reportlab) is missing."
        
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
    
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=20,
        textColor=colors.HexColor('#6366f1'),
        spaceAfter=12
    )
    
    h2_style = ParagraphStyle(
        'SectionHeading',
        parent=styles['Heading2'],
        fontSize=14,
        textColor=colors.HexColor('#1e293b'),
        spaceBefore=14,
        spaceAfter=8
    )
    
    normal_style = styles['Normal']
    
    elements = []
    
    # Title
    elements.append(Paragraph(doc_title, title_style))
    elements.append(Paragraph("AI-Powered Accessibility & Cognitive Inclusion Intelligence Report", normal_style))
    elements.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#cbd5e1'), spaceBefore=8, spaceAfter=14))
    
    # KPI Scorecard Table
    elements.append(Paragraph("Executive Summary KPIs", h2_style))
    kpi_data = [
        ["Metric", "Value"],
        ["Accessibility Score", f"{analysis.get('accessibility_score', 0)} / 100"],
        ["Readability Score (Flesch)", f"{analysis.get('readability_score', 0)}"],
        ["Reading Grade Level", f"Grade {analysis.get('grade_level', 0)}"],
        ["Cognitive Complexity Index", f"{analysis.get('cognitive_complexity', 0)} / 100"],
        ["Total Violations", f"{analysis.get('violations_count', 0)} issues"]
    ]
    
    kpi_table = Table(kpi_data, colWidths=[200, 250])
    kpi_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#6366f1')),
        ('TEXTCOLOR', (0,0), (-1,0), colors.white),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#e2e8f0')),
        ('PADDING', (0,0), (-1,-1), 6)
    ]))
    elements.append(kpi_table)
    elements.append(Spacer(1, 14))
    
    # Explainable AI Rationale
    if analysis.get("xai_explanation"):
        elements.append(Paragraph("Explainable AI (XAI) Score Rationale", h2_style))
        elements.append(Paragraph(analysis["xai_explanation"], normal_style))
        elements.append(Spacer(1, 12))
        
    # Violations List
    elements.append(Paragraph("Detected Accessibility & Cognitive Violations", h2_style))
    issues = analysis.get("issues", [])
    if not issues:
        elements.append(Paragraph("No accessibility issues detected. Great job!", normal_style))
    else:
        for idx, iss in enumerate(issues, 1):
            issue_text = f"<b>#{idx}. {iss.get('title')}</b> [{iss.get('severity')}]<br/>" \
                         f"<i>Category:</i> {iss.get('category')}<br/>" \
                         f"<i>Explanation:</i> {iss.get('explanation')}<br/>" \
                         f"<i>Recommendation:</i> {iss.get('suggestion')}"
            elements.append(Paragraph(issue_text, normal_style))
            elements.append(Spacer(1, 8))
            
    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()
